import {
  Inject,
  Injectable,
  Logger,
  NotFoundException,
  BadRequestException,
} from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { ConfigService } from '@nestjs/config';
import { DataSource, EntityManager, FindOptionsWhere, Repository } from 'typeorm';
import { Wallet } from '../../database/entities/wallet.entity';
import { WalletAccount } from '../../database/entities/wallet-account.entity';
import { CustodyAccount } from '../../database/entities/custody-account.entity';
import { DepositAddress } from '../../database/entities/deposit-address.entity';
import { Transaction } from '../../database/entities/transaction.entity';
import { ASSET_REGISTRY, enabledAssets, getAsset } from '../../config/assets';
import {
  BLOCKCHAIN_PROVIDER,
  BlockchainProvider,
  ChainAccountMaterial,
} from '../../providers/provider.interface';
import { SECRET_STORE, SecretStore } from '../../secrets/secret-store';
import { LedgerService } from '../../ledger/ledger.service';
import { errMsg } from '../../common/errors';

@Injectable()
export class WalletsService {
  private readonly logger = new Logger(WalletsService.name);

  constructor(
    @InjectRepository(Wallet) private readonly wallets: Repository<Wallet>,
    @InjectRepository(WalletAccount) private readonly accounts: Repository<WalletAccount>,
    @InjectRepository(CustodyAccount) private readonly custody: Repository<CustodyAccount>,
    @InjectRepository(DepositAddress) private readonly addresses: Repository<DepositAddress>,
    @InjectRepository(Transaction) private readonly txs: Repository<Transaction>,
    @Inject(BLOCKCHAIN_PROVIDER) private readonly provider: BlockchainProvider,
    private readonly ledger: LedgerService,
    private readonly config: ConfigService,
    private readonly dataSource: DataSource,
    @Inject(SECRET_STORE) private readonly secretStore: SecretStore,
  ) {}

  /**
   * Creates a wallet for a Bitlily user: one WalletAccount per enabled CHAIN.
   * All assets on a chain (ETH, USDT_ETH, USDC_ETH…) share the chain's xpub
   * and derivation counter — this is what keeps deposit addresses unique
   * per order even when multiple assets settle on one chain.
   * Wallet material (mnemonic/keys) is generated by the provider and handed
   * to the secret store — only xpubs/base addresses are persisted here.
   * Idempotent on (appId, externalUserId) — the same user ID under two
   * different apps creates two separate wallets.
   */
  async createWallet(externalUserId: string, appId: string): Promise<Wallet> {
    const existing = await this.wallets.findOne({ where: { externalUserId, appId } });
    if (existing) return existing;

    const chains = [...new Set(enabledAssets().map((a) => a.chain))];
    const useKms = this.config.get('tatum.useKms') === true;

    // Two account models:
    //  KMS   — all wallets share the chain's enrolled custody account
    //          (custody_accounts row: xpub + signatureId). Material never
    //          exists here; deposit addresses are index-derived under one
    //          master wallet, signed by signatureId + index.
    //  dev   — per-wallet material generated via the provider and enrolled
    //          into the env store (discarded); sends sign via TESTNET_PK_*.
    let enrolled: {
      chain: string;
      material: { xpub?: string; baseAddress?: string };
      secretRef: string | null;
    }[] = [];
    if (useKms) {
      for (const chain of chains) {
        const custody = await this.custody.findOne({ where: { chain } });
        if (!custody) {
          throw new BadRequestException(
            `No enrolled custody wallet for ${chain} — run ` +
            `tatum-kms generatemanagedwallet ${chain} on the KMS host, then ` +
            `POST /api/v1/admin/custody.`,
          );
        }
        enrolled.push({
          chain,
          material: { xpub: custody.xpub, baseAddress: custody.baseAddress },
          secretRef: custody.secretRef,
        });
      }
    } else {
      for (const chain of chains) {
        const material = await this.provider.createChainAccount(chain);
        // HD chains return a mnemonic; account-model chains (SOL) return the
        // key itself in material.mnemonic — map by shape, not chain name.
        const secretRef = await this.secretStore.enroll(chain, {
          mnemonic: material.xpub ? material.mnemonic : undefined,
          privateKey: material.baseAddress ? material.mnemonic : undefined,
        });
        enrolled.push({ chain, material, secretRef });
      }
    }

    const wallet = await this.dataSource.transaction(async (em) => {
      const w = await em.save(em.create(Wallet, { externalUserId, appId }));
      for (const { chain, material, secretRef } of enrolled) {
        await em.save(
          em.create(WalletAccount, {
            wallet: w,
            chain,
            xpub: material.xpub,
            baseAddress: material.baseAddress,
            secretRef,
          }),
        );
      }
      return w;
    });
    return this.wallets.findOneOrFail({ where: { id: wallet.id }, relations: ['accounts'] });
  }

  async getWalletOrThrow(id: string, appId: string): Promise<Wallet> {
    // Scoped by appId — a wallet owned by another tenant is invisible (404,
    // not 403: don't confirm the ID exists to a foreign app).
    const w = await this.wallets.findOne({
      where: { id, appId },
      relations: ['accounts'],
    });
    if (!w) throw new NotFoundException(`Wallet ${id} not found`);
    return w;
  }

  /**
   * Generates (or reuses) a deposit address for an asset.
   * `persistent: true` = exchange model (Bybit-style): the wallet's ONE
   * permanent address for this chain — first call derives it, later calls
   * return the same row. Default = per-payment address with TTL +
   * `reference` tying it to an order/invoice (Selly-style flow).
   */
  async generateDepositAddress(
    walletId: string,
    appId: string,
    assetCode: string,
    reference?: string,
    expiresInMinutes?: number,
    persistent?: boolean,
  ): Promise<DepositAddress> {
    const asset = getAsset(assetCode);
    if (!asset) throw new BadRequestException(`Unsupported asset: ${assetCode}`);
    if (persistent && expiresInMinutes != null) {
      throw new BadRequestException(
        'persistent addresses never expire — expiresInMinutes cannot be combined with persistent',
      );
    }

    const ttl = expiresInMinutes ?? this.config.get<number>('detection.addressTtlMinutes');
    const expiresAt = persistent ? null : ttl ? new Date(Date.now() + ttl * 60_000) : null;

    return this.dataSource.transaction(async (em) => {
      // The account is per-CHAIN: USDC_ETH deposits derive from the wallet's
      // ETH account's shared index, so same-chain assets never collide.
      const account = await em.findOne(WalletAccount, {
        where: { wallet: { id: walletId, appId }, chain: asset.chain },
        lock: { mode: 'pessimistic_write' },
      });
      if (!account) throw new NotFoundException(
        `No ${asset.chain} account for wallet ${walletId}`,
      );

      // Persistent (exchange-style): one address per (wallet, asset) —
      // reuse the existing row, promote any expiring row to permanent.
      // reference is order-level metadata; it doesn't apply to a permanent
      // user address, so a persistent request never overwrites it.
      if (persistent) {
        // Prefer the permanent row; else reuse the newest (promote it to
        // permanent rather than deriving yet another address).
        const [existing] = await em.find(DepositAddress, {
          where: { account: { id: account.id }, asset: asset.code },
          order: { expiresAt: 'DESC', createdAt: 'DESC' },
          take: 1,
        });
        if (existing) {
          existing.status = 'active';
          existing.expiresAt = null;
          const saved = await em.save(existing);
          await this.ensureSameChainWatches(
            em, account, saved.address, saved.derivationIndex, asset.code, null, reference,
          );
          return saved;
        }
      }

      // Account-model chains (SOL) have a single base address and cannot
      // derive fresh ones. Reuse the active row: refresh reference/expiry
      // instead of colliding on the (address, asset) unique index. Per-order
      // SOL attribution needs memo/keypair-per-order — tracked as a gap.
      if (account.baseAddress) {
        // Reuse THE row regardless of status — the (account,address,asset)
        // unique index means inserting another row 500s forever once the
        // first retires (live-caught: SOL wallets broke after one cycle).
        const existing = await em.findOne(DepositAddress, {
          where: { account: { id: account.id }, asset: asset.code },
        });
        if (existing) {
          existing.status = 'active';
          // A permanent row (persistent, or TTL=0 config) is never demoted
          // by a per-payment request — account-model chains have only this
          // one address, so stamping an expiry would silently retire the
          // user's saved deposit address. Reference is order metadata and
          // likewise must not bleed onto a permanent user address.
          const permanent = existing.expiresAt === null;
          if (!permanent) {
            existing.reference = reference ?? existing.reference;
            existing.expiresAt = expiresAt;
          }
          const saved = await em.save(existing);
          await this.ensureSameChainWatches(
            em, account, saved.address, saved.derivationIndex, asset.code,
            permanent ? null : expiresAt, reference,
          );
          return saved;
        }
      }

      const index = account.baseAddress ? 0 : await this.allocIndex(em, account.chain);
      const address = await this.provider.generateDepositAddress(
        { chain: account.chain as any, xpub: account.xpub, baseAddress: account.baseAddress },
        index,
      );

      const dep = await em.save(
        em.create(DepositAddress, {
          account,
          address,
          chain: account.chain,
          asset: asset.code,
          derivationIndex: index,
          reference,
          expiresAt,
        }),
      );

      await this.ensureSameChainWatches(
        em, account, address, index, asset.code, expiresAt, reference,
      );

      // Webhook mode registers provider-side monitoring; polling mode relies
      // on the DepositPoller — no per-address subscription cost.
      const useWebhooks = this.config.get('detection.strategy') === 'webhook';
      if (useWebhooks && this.provider.createAddressSubscription) {
        try {
          const sub = await this.provider.createAddressSubscription(
            address,
            account.chain as any,
          );
          dep.subscriptionId = sub.subscriptionId;
          await em.save(dep);
        } catch (e) {
          this.logger.warn(`Subscription failed for ${address}: ${errMsg(e)}`);
        }
      }
      return dep;
    });
  }

  /**
   * Global HD index allocation. With a shared custody xpub (KMS mode)
   * per-wallet counters would collide across wallets, so the counter lives
   * at chain level and increments atomically — safe under concurrency.
   */
  private async allocIndex(em: EntityManager, chain: string): Promise<number> {
    // Index 0 is RESERVED as the treasury — counters start at 2 so the
    // first deposit gets index 1. Seeding at 1 meant the first deposit
    // address derived as the treasury itself (live-caught collision).
    const [row] = await em.query(
      `INSERT INTO chain_counters (chain, next_index) VALUES ($1, 2)
       ON CONFLICT (chain) DO UPDATE
       SET next_index = GREATEST(chain_counters.next_index + 1, 2)
       RETURNING next_index`,
      [chain],
    );
    return Math.max(row.next_index - 1, 1);
  }

  /**
   * Wrong-asset recovery: watch a generated address for EVERY enabled
   * same-chain asset, so a USDC payment to an ETH-labeled address is
   * detected instead of stranded. Costs one extra balance read per
   * same-chain asset per poll — bounded by the registry; recoverability
   * wins over credit thrift for a payments product.
   */
  private async ensureSameChainWatches(
    em: EntityManager,
    account: WalletAccount,
    address: string,
    derivationIndex: number,
    primaryAsset: string,
    expiresAt: Date | null,
    reference?: string,
  ): Promise<void> {
    for (const other of enabledAssets().filter(
      (a) => a.chain === account.chain && a.code !== primaryAsset,
    )) {
      // Scoped to THIS account — shared custody addresses (SOL) legitimately
      // exist as rows under other wallets' accounts too; an unscoped lookup
      // would mutate a foreign wallet's watch row and leave ours uncreated.
      const row = await em.findOne(DepositAddress, {
        where: { account: { id: account.id }, address, asset: other.code },
      });
      if (row) {
        // Refresh when retired/expired; for a permanent parent (expiresAt
        // null) promote any expiring watch — a permanent address with
        // expiring recovery rows would silently lose wrong-asset coverage.
        // Symmetrically, a permanent watch row is NEVER demoted: JS
        // `null < Date` is true, so without the guard an expiring parent
        // would stamp an expiry onto the permanent row.
        const stale =
          row.expiresAt === null
            ? false
            : expiresAt
              ? row.expiresAt < expiresAt
              : true;
        if (row.status !== 'active' || stale) {
          row.status = 'active';
          row.expiresAt = expiresAt;
          await em.save(row);
        }
        continue;
      }
      await em.save(
        em.create(DepositAddress, {
          account,
          address,
          chain: account.chain,
          asset: other.code,
          derivationIndex,
          reference,
          expiresAt,
        }),
      );
    }
  }

  /**
   * Re-watch an address for an asset — recovery path for late payments to
   * expired addresses and wrong-asset sends predating auto-watch.
   * Restricted to addresses that already belong to this wallet: watching
   * arbitrary foreign addresses would credit funds we cannot sweep.
   */
  async watchAddress(
    walletId: string,
    appId: string,
    address: string,
    assetCode: string,
    expiresInMinutes?: number,
  ): Promise<DepositAddress> {
    const asset = getAsset(assetCode);
    if (!asset) throw new BadRequestException(`Unsupported asset: ${assetCode}`);

    const ttl = expiresInMinutes ?? this.config.get<number>('detection.addressTtlMinutes');
    const expiresAt = ttl ? new Date(Date.now() + ttl * 60_000) : null;

    return this.dataSource.transaction(async (em) => {
      const row = await em.findOne(DepositAddress, {
        where: { address, asset: asset.code, account: { wallet: { id: walletId, appId } } },
        relations: ['account'],
      });
      if (row) {
        row.status = 'active';
        // Permanent rows stay permanent — /watch revives/extends expiring
        // rows but must never demote a persistent address to expirable.
        if (row.expiresAt !== null) row.expiresAt = expiresAt;
        return em.save(row);
      }
      // No watch row for this asset — allowed only if the address is one of
      // this wallet's own deposit addresses on the asset's chain.
      const anyRow = await em.findOne(DepositAddress, {
        where: { address, account: { wallet: { id: walletId, appId } } },
        relations: ['account'],
      });
      if (!anyRow || anyRow.chain !== asset.chain) {
        throw new BadRequestException(
          `Address ${address} is not a ${asset.chain} deposit address on this wallet`,
        );
      }
      return em.save(
        em.create(DepositAddress, {
          account: anyRow.account,
          address,
          chain: asset.chain,
          asset: asset.code,
          derivationIndex: anyRow.derivationIndex,
          reference: anyRow.reference,
          expiresAt,
        }),
      );
    });
  }

  /**
   * Provision (or return existing) PERMANENT per-chain addresses for the
   * given assets — the exchange-model lazy mint folded into POST /wallets.
   * Each entry flows through the same persistent path as the retired
   * POST /wallets/:id/addresses route.
   */
  async ensureDepositAddresses(walletId: string, appId: string, assets: string[]) {
    const out = [];
    for (const asset of assets) {
      out.push(
        await this.generateDepositAddress(walletId, appId, asset, undefined, undefined, true),
      );
    }
    return out;
  }

  /**
   * Aggregate wallet read — the single GET behind the 2-endpoint surface.
   * include folds in balances (ledger), addresses (watch rows) and/or a
   * paginated transaction page. Anything not included stays off the wire.
   */
  async getWalletView(
    id: string,
    appId: string,
    q: {
      include?: string;
      txLimit?: number;
      txPage?: number;
      chain?: string;
      asset?: string;
    },
  ) {
    const wallet = await this.getWalletOrThrow(id, appId);
    const inc = new Set(
      (q.include ?? 'balances,addresses').split(',').map((s) => s.trim()).filter(Boolean),
    );
    const view: Record<string, unknown> = { ...wallet };
    if (inc.has('balances')) view.balances = await this.ledger.getBalances(id);
    if (inc.has('addresses')) {
      view.addresses = await this.addresses.find({
        where: { account: { wallet: { id } } },
        order: { createdAt: 'DESC' },
      });
    }
    if (inc.has('transactions')) {
      const limit = Math.min(Math.max(q.txLimit ?? 20, 1), 100);
      const page = Math.max(q.txPage ?? 1, 1);
      const where: FindOptionsWhere<Transaction> = { wallet: { id } };
      if (q.asset) {
        const asset = getAsset(q.asset);
        if (!asset) throw new BadRequestException(`Unsupported asset: ${q.asset}`);
        where.asset = asset.code;
      }
      if (q.chain) {
        const chain = q.chain.toUpperCase();
        const valid = new Set<string>(ASSET_REGISTRY.map((a) => a.chain));
        if (!valid.has(chain)) {
          throw new BadRequestException(
            `Unsupported chain: ${q.chain} (supported: ${[...valid].join(', ')})`,
          );
        }
        where.chain = chain;
      }
      view.transactions = await this.txs.find({
        where,
        order: { createdAt: 'DESC' },
        take: limit,
        skip: (page - 1) * limit,
      });
    }
    return view;
  }

  async getBalances(walletId: string, appId: string) {
    await this.getWalletOrThrow(walletId, appId);
    return this.ledger.getBalances(walletId);
  }

  async getTransactions(walletId: string, appId: string) {
    await this.getWalletOrThrow(walletId, appId);
    return this.txs.find({
      where: { wallet: { id: walletId } },
      order: { createdAt: 'DESC' },
      take: 200,
    });
  }

  async listAddresses(walletId: string, appId: string) {
    await this.getWalletOrThrow(walletId, appId);
    return this.addresses.find({
      where: { account: { wallet: { id: walletId } } },
      order: { createdAt: 'DESC' },
    });
  }
}
