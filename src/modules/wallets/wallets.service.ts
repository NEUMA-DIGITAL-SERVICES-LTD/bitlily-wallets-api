@Injectable()
export class WalletsService {
  private readonly logger = new Logger(WalletsService.name);

  constructor(
    @InjectRepository(Wallet) private readonly wallets: Repository<Wallet>,
    @InjectRepository(WalletAccount) private readonly accounts: Repository<WalletAccount>,
    @InjectRepository(CustodyAccount) private readonly custody: Repository<CustodyAccount>,
    @InjectRepository(DepositAddress) private readonly addresses: Repository<DepositAddress>,
    @InjectRepository(Transaction) private readonly txs: Repository<Transaction>,
    @Inject(BLOCKCHAIN_PROVIDER) private readonly provider: BlockchainProvider,
    private readonly ledger: LedgerService,
    private readonly config: ConfigService,
    private readonly dataSource: DataSource,
    @Inject(SECRET_STORE) private readonly secretStore: SecretStore,
  ) {}

  /**
   * Creates a wallet for a Bitlily user: one WalletAccount per enabled CHAIN.
   * All assets on a chain (ETH, USDT_ETH, USDC_ETH…) share the chain's xpub
   * and derivation counter — this is what keeps deposit addresses unique
   * per order even when multiple assets settle on one chain.
   * Wallet material (mnemonic/keys) is generated by the provider and handed
   * to the secret store — only xpubs/base addresses are persisted here.
   * Idempotent on (appId, externalUserId) — the same user ID under two
   * different apps creates two separate wallets.
   */
  async createWallet(externalUserId: string, appId: string): Promise<Wallet> {
    const existing = await this.wallets.findOne({ where: { externalUserId, appId } });
    if (existing) return existing;

    const chains = [...new Set(enabledAssets().map((a) => a.chain))];

    // Two account models:
    //  KMS   — all wallets share the chain's enrolled custody account
    //          (custody_accounts row: xpub + signatureId). Material never
    //          exists here; deposit addresses are index-derived under one
    //          master wallet, signed by signatureId + index.
    //  dev   — per-wallet material generated via the provider and enrolled
    //          into the env store (discarded); sends sign via TESTNET_PK_*.
    let enrolled: {
      chain: string;
      material: { xpub?: string; baseAddress?: string };
      secretRef: string | null;
    }[] = [];
    for (const chain of chains) {
      enrolled.push({ chain, ...(await this.chainMaterial(chain)) });
    }

    try {
      const wallet = await this.dataSource.transaction(async (em) => {
        const w = await em.save(em.create(Wallet, { externalUserId, appId }));
        for (const { chain, material, secretRef } of enrolled) {
          await em.save(
            em.create(WalletAccount, {
              wallet: w,
              chain,
              xpub: material.xpub,
              baseAddress: material.baseAddress,
              secretRef,
              // Shared-custody chains (SOL) attribute deposits by this memo.
              memo: material.baseAddress ? await this.uniqueMemo(em) : null,
            }),
          );
        }
        return w;
      });
      return this.wallets.findOneOrFail({ where: { id: wallet.id }, relations: ['accounts'] });
    } catch (e) {
      // "Call it freely" invites concurrent first-creates: both pass the
      // existence check, the loser's INSERT violates UQ(appId,
      // externalUserId) — the idempotent answer is the winner's wallet.
      if (errCode(e) === '23505') {
        const winner = await this.wallets.findOne({ where: { externalUserId, appId } });
        if (winner) return winner;
      }
      throw e;
    }
  }

  /**
   * Resolves chain-level account material — KMS mode borrows the enrolled
   * custody account (xpub/baseAddress + signatureId ref); dev mode generates
   * per-wallet material through the provider and enrolls it into the
   * secret store.
   */
  private async chainMaterial(chain: Chain): Promise<{
    material: { xpub?: string; baseAddress?: string };
    secretRef: string | null;
  }> {
    if (this.config.get('tatum.useKms') === true) {
      const custody = await this.custody.findOne({ where: { chain } });
      if (!custody) {
        throw new BadRequestException(
          `No enrolled custody wallet for ${chain} — run ` +
          `tatum-kms generatemanagedwallet ${chain} on the KMS host, then ` +
          `POST /api/v1/admin/custody.`,
        );
      }
      return {
        material: { xpub: custody.xpub, baseAddress: custody.baseAddress },
        secretRef: custody.secretRef,
      };
    }
    const material = await this.provider.createChainAccount(chain);
    // HD chains return a mnemonic; account-model chains (SOL) return the
    // key itself in material.mnemonic — map by shape, not chain name.
    const secretRef = await this.secretStore.enroll(chain, {
      mnemonic: material.xpub ? material.mnemonic : undefined,
      privateKey: material.baseAddress ? material.mnemonic : undefined,
    });
    return { material, secretRef };
  }

  /**
   * Lazily create WalletAccounts for chains the wallet predates — a wallet
   * created before a chain was enabled must still be able to take a first
   * deposit on it. orIgnore: a concurrent ensure for the same (wallet,
   * chain) loses the insert race harmlessly — the winner's row carries the
   * same custody material.
   */
  private async ensureChainAccounts(
    walletId: string,
    appId: string,
    chains: string[],
  ): Promise<void> {
    const have = new Set(
      (await this.accounts.find({ where: { wallet: { id: walletId, appId } } }))
        .map((a) => a.chain),
    );
    for (const chain of chains.filter((c) => !have.has(c))) {
      const { material, secretRef } = await this.chainMaterial(chain as Chain);
      await this.accounts
        .createQueryBuilder()
        .insert()
        .values({
          wallet: { id: walletId } as Wallet,
          chain,
          xpub: material.xpub ?? null,
          baseAddress: material.baseAddress ?? null,
          secretRef,
          // Shared-custody chains attribute deposits by memo — mint one at
          // account creation so every watch row on this account resolves
          // through it. Uniqueness is the partial index's job; orIgnore only
          // covers the (wallet, chain) race, not a memo collision.
          memo: material.baseAddress ? await this.uniqueMemo(this.accounts.manager) : null,
        })
        .orIgnore()
        .execute();
    }
  }

  /**
   * The wallet's permanent deposit addresses, grouped one row per address:
   * {address, chain, assets[], expiresAt:null}. Same-chain assets share the
   * address, so per-asset rows would repeat it — grouping is the honest
   * representation of the exchange model. Expired/temporary watch rows are
   * ops internals, not user-facing addresses.
   */
  async permanentAddresses(walletId: string) {
    let rows = await this.addresses.find({
      where: {
        account: { wallet: { id: walletId } },
        expiresAt: IsNull(),
        status: 'active',
      },
      relations: ['account'],
      order: { createdAt: 'ASC' },
    });
    type AddressGroup = {
      address: string;
      chain: string;
      assets: string[];
      expiresAt: null;
      memo?: string;
      memoRequired?: boolean;
    };
    // Legacy shared-custody SOL accounts (pre-pool) still watch the shared
    // baseAddress + memo. Migrate them to a pooled unique address on first
    // read — attribution moves from memo to address, matching every other
    // chain. The shared rows STAY active as a memo-attributed catch-all:
    // sends to the old address still credit (or queue unattributed when
    // memo-less); they're only hidden from this response so clients see
    // the per-user address, never the shared one.
    if (this.config.get('detection.solUniqueDeposits')) {
      const seen = new Set<string>();
      let migrated = false;
      for (const r of rows) {
        const a = r.account;
        if (!a?.baseAddress || a.chain !== 'SOL' || seen.has(a.id)) continue;
        seen.add(a.id);
        migrated = (await this.migrateSharedSolAccount(a)) || migrated;
      }
      if (migrated) {
        rows = await this.addresses.find({
          where: {
            account: { wallet: { id: walletId } },
            expiresAt: IsNull(),
            status: 'active',
          },
          relations: ['account'],
          order: { createdAt: 'ASC' },
        });
      }
      // Hide each shared-address group once its account has a pooled row —
      // the pooled address is what clients should show/send to.
      const pooledAccounts = new Set(
        rows
          .filter((r) => r.account?.baseAddress && r.address !== r.account.baseAddress)
          .map((r) => r.account!.id),
      );
      rows = rows.filter(
        (r) =>
          r.address !== r.account?.baseAddress || !pooledAccounts.has(r.account!.id),
      );
    }
    const grouped = new Map<string, AddressGroup>();
    for (const r of rows) {
      // Backfill memos on shared-custody accounts that predate the memo
      // model — a memo-less SOL address shown to a client would funnel
      // that user's deposits into the ops review queue.
      if (r.account?.baseAddress && !r.account.memo) {
        await this.ensureAccountMemo(this.dataSource.manager, r.account);
      }
      const g: AddressGroup =
        grouped.get(r.address) ??
        { address: r.address, chain: r.chain, assets: [], expiresAt: null };
      // memoRequired only when this row IS the shared custody address —
      // a pooled per-user address needs no memo (it's uniquely theirs).
      if (r.account?.memo && r.address === r.account.baseAddress) {
        g.memo = r.account.memo;
        g.memoRequired = true;
      }
      if (!g.assets.includes(r.asset)) g.assets.push(r.asset);
      grouped.set(r.address, g);
    }
    // Deterministic ordering: native first, then alphabetical — row
    // createdAt ties returned arbitrary orders between identical calls.
    return [...grouped.values()].map((g) => ({
      ...g,
      assets: [...g.assets].sort((a, b) => {
        const na = getAsset(a)?.type === 'native' ? 0 : 1;
        const nb = getAsset(b)?.type === 'native' ? 0 : 1;
        return na - nb || a.localeCompare(b);
      }),
    }));
  }

  async getWalletOrThrow(id: string, appId: string): Promise<Wallet> {
    // Scoped by appId — a wallet owned by another tenant is invisible (404,
    // not 403: don't confirm the ID exists to a foreign app).
    const w = await this.wallets.findOne({
      where: { id, appId },
      relations: ['accounts'],
    });
    if (!w) throw new NotFoundException(`Wallet ${id} not found`);
    return w;
  }

  /**
   * Tenant-scoped lookup by the app's own user id — the read half of
   * get-or-create. 404 (not create) when absent: this backs GET /wallets,
   * a safe method that must never provision.
   */
  async findByExternalId(externalUserId: string, appId: string): Promise<Wallet> {
    const w = await this.wallets.findOne({ where: { externalUserId, appId } });
    if (!w) throw new NotFoundException(`No wallet for externalUserId ${externalUserId}`);
    return w;
  }

  /**
   * Generates (or reuses) a deposit address for an asset — exchange model
   * only: the wallet's ONE permanent address per (chain, asset). First
   * call derives it, later calls return the same row; a legacy expiring
   * row is promoted to permanent rather than replaced.
   */
  async generateDepositAddress(
    walletId: string,
    appId: string,
    assetCode: string,
  ): Promise<DepositAddress> {
    const asset = getAsset(assetCode);
    if (!asset) throw new BadRequestException(`Unsupported asset: ${assetCode}`);

    return this.dataSource.transaction(async (em) => {
      // The account is per-CHAIN: USDC_ETH deposits derive from the wallet's
      // ETH account's shared index, so same-chain assets never collide.
      const account = await em.findOne(WalletAccount, {
        where: { wallet: { id: walletId, appId }, chain: asset.chain },
        lock: { mode: 'pessimistic_write' },
      });
      if (!account) throw new NotFoundException(
        `No ${asset.chain} account for wallet ${walletId}`,
      );

      // One address per (wallet, asset): reuse the existing row, promote
      // any legacy expiring row to permanent rather than deriving again.
      const [existing] = await em.find(DepositAddress, {
        where: { account: { id: account.id }, asset: asset.code },
        order: { expiresAt: 'DESC', createdAt: 'DESC' },
        take: 1,
      });
      if (existing) {
        existing.status = 'active';
        existing.expiresAt = null;
        await this.ensureAccountMemo(em, account);
        const saved = await em.save(existing);
        await this.ensureSameChainWatches(
          em, account, saved.address, saved.derivationIndex, asset.code,
        );
        return saved;
      }

      // Unique-address model for chains that can't derive addresses at
      // runtime — SOL is ed25519 AND Tatum's managed SOL wallet is a
      // single private key (no index derivation — verified live: every
      // index returns the same address). Unique SOL addresses are therefore
      // whole keypairs minted on the KMS host into address_pool, one
      // signatureId each. The wallet's pooled address is permanent: sweeps
      // sign with the row's own signatureId; no memo needed.
      if (asset.chain === 'SOL' && this.config.get('detection.solUniqueDeposits')) {
        const pooled = await this.allocatePoolAddress(em, account);
        if (pooled) {
          let row = await em.findOne(DepositAddress, {
            where: {
              account: { id: account.id },
              address: pooled.address,
              asset: asset.code,
            },
          });
          if (!row) {
            row = em.create(DepositAddress, {
              account,
              address: pooled.address,
              chain: account.chain,
              asset: asset.code,
              // Pooled SOL rows sign by signatureId, not index — the dep
              // row carries null and sweeps resolve the pool row by address.
              derivationIndex: null,
              expiresAt: null, // per-user permanent — the user's address forever
            });
          }
          row.status = 'active';
          const saved = await em.save(row);
          await this.ensureSameChainWatches(
            em, account, saved.address, saved.derivationIndex, asset.code,
          );
          return saved;
        }
        // Pool exhausted — FAIL, don't fall back. A shared+memo SOL row
        // breaks the per-user-address contract every other chain offers
        // (the user is shown an address that isn't theirs). 503 because
        // it's transient: ops seeds the pool and provisioning resumes.
        this.logger.error(
          'SOL address pool exhausted — refusing wallet provisioning. ' +
          'Seed more addresses: scripts/sol-pool-seed.js → POST /admin/address-pool.',
        );
        throw new ServiceUnavailableException(
          'SOL deposit addresses temporarily exhausted — ops has been ' +
          'alerted; retry shortly.',
        );
      }

      const index = account.baseAddress ? 0 : await this.allocIndex(em, account.chain);
      const address = await this.provider.generateDepositAddress(
        { chain: account.chain as any, xpub: account.xpub, baseAddress: account.baseAddress },
        index,
      );

      const dep = await em.save(
        em.create(DepositAddress, {
          account,
          address,
          chain: account.chain,
          asset: asset.code,
          derivationIndex: index,
          expiresAt: null,
        }),
      );
      await this.ensureAccountMemo(em, account);

      await this.ensureSameChainWatches(
        em, account, address, index, asset.code,
      );

      // Webhook mode registers provider-side monitoring; polling mode relies
      // on the DepositPoller — no per-address subscription cost.
      const useWebhooks = this.config.get('detection.strategy') === 'webhook';
      if (useWebhooks && this.provider.createAddressSubscription) {
        try {
          const sub = await this.provider.createAddressSubscription(
            address,
            account.chain as any,
          );
          dep.subscriptionId = sub.subscriptionId;
          await em.save(dep);
        } catch (e) {
          this.logger.warn(`Subscription failed for ${address}: ${errMsg(e)}`);
        }
      }
      return dep;
    });
  }

  /**
   * Allocates the wallet's pooled SOL address — reuses the row already
   * assigned to this account, else claims the lowest free index.
   * pessimistic_write on the claimed row serializes concurrent allocations;
   * two wallets racing the same free row resolve on the FK update, and the
   * loser re-reads the next free row on retry.
   */
  private async allocatePoolAddress(
    em: EntityManager,
    account: WalletAccount,
  ): Promise<AddressPool | null> {
    const assigned = await em.findOne(AddressPool, {
      where: { account: { id: account.id } },
    });
    if (assigned) return assigned;
    for (let attempt = 0; attempt < 3; attempt++) {
      const free = await em.findOne(AddressPool, {
        where: { chain: account.chain, account: IsNull() },
        order: { createdAt: 'ASC' },
      });
      if (!free) return null;
      const claimed = await em
        .createQueryBuilder()
        .update(AddressPool)
        .set({ account, assignedAt: new Date() })
        .where('id = :id AND wallet_account_id IS NULL', { id: free.id })
        .execute();
      if (claimed.affected === 1) {
        free.account = account;
        free.assignedAt = new Date();
        return free;
      }
      // Lost the claim race — loop and take the next free row.
    }
    return null;
  }

  /**
   * Migrates a shared-custody SOL account to the pooled unique-address
   * model: claims a pool row, then mirrors the account's shared-address
   * watch assets onto the pooled address. Shared rows are left active —
   * they're the catch-all for deposits still arriving at the old address.
   * Returns true when pooled rows exist afterward (already migrated or
   * just created); false when the pool is empty and the account must stay
   * on shared+memo for now.
   */
  private async migrateSharedSolAccount(account: WalletAccount): Promise<boolean> {
    const base = account.baseAddress;
    if (!base) return false; // not a shared-custody account
    return this.dataSource.transaction(async (em) => {
      // Lock the account row first — two concurrent first-reads would each
      // pass allocatePoolAddress's assigned-check and claim DIFFERENT pool
      // rows for the same account, permanently splitting its address set.
      await em.findOneOrFail(WalletAccount, {
        where: { id: account.id },
        lock: { mode: 'pessimistic_write' },
      });
      const pooled = await this.allocatePoolAddress(em, account);
      if (!pooled) {
        this.logger.warn(
          `SOL pool exhausted — account ${account.id} stays on shared ` +
          `address ${base} + memo until ops reseeds the pool.`,
        );
        return false;
      }
      const shared = await em.find(DepositAddress, {
        where: { account: { id: account.id }, address: base },
      });
      for (const s of shared) {
        const row = await em.findOne(DepositAddress, {
          where: {
            account: { id: account.id },
            address: pooled.address,
            asset: s.asset,
          },
        });
        if (row) {
          if (row.status !== 'active') {
            row.status = 'active';
            await em.save(row);
          }
          continue;
        }
        await em.save(
          em.create(DepositAddress, {
            account,
            address: pooled.address,
            chain: account.chain,
            asset: s.asset,
            derivationIndex: null,
            expiresAt: null,
          }),
        );
      }
      // Same parity provisioning offers: the pooled address watches EVERY
      // enabled SOL asset, not just ones the shared row happened to have —
      // a USDC_SOL send to a pooled address with no token watch is
      // invisible, not merely unattributed. `primary` picks any already-
      // mirrored asset (SOL preferred); a non-asset sentinel when `shared`
      // is empty so the exclusion never skips a real asset.
      const primary = shared.find((s) => s.asset === 'SOL')
        ? 'SOL'
        : shared[0]?.asset ?? 'SOL-missing';
      await this.ensureSameChainWatches(
        em, account, pooled.address, null, primary,
      );
      return true;
    });
  }

  /**
   * Shared-custody accounts (SOL) attribute deposits by memo — assign one
   * at provisioning and backfill accounts that predate the memo model
   * whenever they're touched. Without a memo a shared-address deposit can
   * only go to the ops review queue, so every live account must carry one.
   */
  private async ensureAccountMemo(
    em: EntityManager,
    account: WalletAccount,
  ): Promise<void> {
    if (account.baseAddress && !account.memo) {
      account.memo = await this.uniqueMemo(em);
      await em.save(account);
    }
  }

  /** Collisions are astronomically unlikely; the unique index is the real
   * guard — this just avoids handing Postgres a violation on a retry loop. */
  private async uniqueMemo(em: EntityManager): Promise<string> {
    for (let i = 0; i < 5; i++) {
      const memo = newDepositMemo();
      const clash = await em.findOne(WalletAccount, { where: { memo } });
      if (!clash) return memo;
    }
    throw new Error('Deposit memo generation exhausted retries');
  }

  /**
   * Global HD index allocation. With a shared custody xpub (KMS mode)
   * per-wallet counters would collide across wallets, so the counter lives
   * at chain level and increments atomically — safe under concurrency.
   */
  private async allocIndex(em: EntityManager, chain: string): Promise<number> {
    // Index 0 is RESERVED as the treasury — counters start at 2 so the
    // first deposit gets index 1. Seeding at 1 meant the first deposit
    // address derived as the treasury itself (live-caught collision).
    const [row] = await em.query(
      `INSERT INTO chain_counters (chain, next_index) VALUES ($1, 2)
       ON CONFLICT (chain) DO UPDATE
       SET next_index = GREATEST(chain_counters.next_index + 1, 2)
       RETURNING next_index`,
      [chain],
    );
    return Math.max(row.next_index - 1, 1);
  }

  /**
   * Wrong-asset recovery: watch a generated address for EVERY enabled
   * same-chain asset, so a USDC payment to an ETH-labeled address is
   * detected instead of stranded. Costs one extra balance read per
   * same-chain asset per poll — bounded by the registry; recoverability
   * wins over credit thrift for a payments product.
   */
  private async ensureSameChainWatches(
    em: EntityManager,
    account: WalletAccount,
    address: string,
    derivationIndex: number | null,
    primaryAsset: string,
  ): Promise<void> {
    for (const other of enabledAssets().filter(
      (a) => a.chain === account.chain && a.code !== primaryAsset,
    )) {
      // Scoped to THIS account — shared custody addresses (SOL) legitimately
      // exist as rows under other wallets' accounts too; an unscoped lookup
      // would mutate a foreign wallet's watch row and leave ours uncreated.
      const row = await em.findOne(DepositAddress, {
        where: { account: { id: account.id }, address, asset: other.code },
      });
      if (row) {
        // Rows are all permanent now — a legacy expiring watch row is
        // promoted, never left to lapse into invisible wrong-asset coverage.
        if (row.status !== 'active' || row.expiresAt !== null) {
          row.status = 'active';
          row.expiresAt = null;
          await em.save(row);
        }
        continue;
      }
      await em.save(
        em.create(DepositAddress, {
          account,
          address,
          chain: account.chain,
          asset: other.code,
          derivationIndex,
          expiresAt: null,
        }),
      );
    }
  }

  /**
   * Re-watch an address for an asset — recovery path for wrong-asset
   * sends (no watch row exists → the deposit is invisible) and for
   * reactivating retired rows.
   * Restricted to addresses that already belong to this wallet: watching
   * arbitrary foreign addresses would credit funds we cannot sweep.
   *
   * Watch rows are ALWAYS permanent — reviving a legacy expirable row
   * promotes it to permanent as well.
   */
  async watchAddress(
    walletId: string,
    appId: string,
    address: string,
    assetCode: string,
  ): Promise<DepositAddress> {
    const asset = getAsset(assetCode);
    if (!asset) throw new BadRequestException(`Unsupported asset: ${assetCode}`);

    return this.dataSource.transaction(async (em) => {
      const row = await em.findOne(DepositAddress, {
        where: { address, asset: asset.code, account: { wallet: { id: walletId, appId } } },
        relations: ['account'],
      });
      if (row) {
        row.status = 'active';
        row.expiresAt = null; // revive = promote to permanent
        return em.save(row);
      }
      // No watch row for this asset — allowed only if the address is one of
      // this wallet's own deposit addresses on the asset's chain.
      const anyRow = await em.findOne(DepositAddress, {
        where: { address, account: { wallet: { id: walletId, appId } } },
        relations: ['account'],
      });
      if (!anyRow || anyRow.chain !== asset.chain) {
        throw new BadRequestException(
          `Address ${address} is not a ${asset.chain} deposit address on this wallet`,
        );
      }
      return em.save(
        em.create(DepositAddress, {
          account: anyRow.account,
          address,
          chain: asset.chain,
          asset: asset.code,
          derivationIndex: anyRow.derivationIndex,
          reference: anyRow.reference,
          expiresAt: null,
        }),
      );
    });
  }

  /**
   * Provision (or return existing) PERMANENT per-chain addresses for the
   * given assets — the exchange-model lazy mint folded into POST /wallets.
   * Dedupes by chain (same-chain assets share one address — one derive per
   * chain), creates missing chain accounts for wallets predating a chain,
   * then derives in parallel across chains (independent counters/accounts).
   */
  async ensureDepositAddresses(walletId: string, appId: string, assets: string[]) {
    const firstAssetOfChain = new Map<string, string>();
    for (const code of assets) {
      const asset = getAsset(code);
      if (!asset) throw new BadRequestException(`Unsupported asset: ${code}`);
      if (!firstAssetOfChain.has(asset.chain)) firstAssetOfChain.set(asset.chain, asset.code);
    }
    const chains = [...firstAssetOfChain.keys()];
    await this.ensureChainAccounts(walletId, appId, chains);
    await Promise.all(
      [...firstAssetOfChain.values()].map((code) =>
        this.generateDepositAddress(walletId, appId, code),
      ),
    );
  }

  /**
   * POST /wallets semantics: get-or-create the wallet, then provision
   * permanent addresses — ALL HD chains when `ensure` is omitted (first
   * call = full deposit-address set, like the custody xpub enrollment),
   * or just the listed assets' chains when provided. Account-model chains
   * (SOL — one shared custody address, no per-user attribution) are skipped
   * in auto-mode but remain reachable via explicit ensure.
   * Response `addresses` is always the wallet's full permanent set.
   */
  async upsertWalletWithAddresses(externalUserId: string, appId: string, ensure?: string[]) {
    const wallet = await this.createWallet(externalUserId, appId);
    // accounts carry xpub + KMS secretRef — internal custody plumbing.
    // Strip before it can reach a client response (a leaked xpub lets an
    // observer derive EVERY future deposit address on that chain).
    const { accounts: _drop, ...pub } = wallet as Wallet & { accounts?: unknown };

    let wanted: string[];
    if (ensure?.length) {
      wanted = ensure;
    } else {
      // Auto-all = every enabled chain's native asset. Shared-custody
      // chains (SOL) are included: the account's deposit memo gives them
      // per-user attribution, so their single address is provisionable
      // like any other.
      const allChains = [...new Set(enabledAssets().map((a) => a.chain))];
      await this.ensureChainAccounts(wallet.id, appId, allChains);
      wanted = enabledAssets()
        .filter((a) => a.type === 'native')
        .map((a) => a.code);
    }

    await this.ensureDepositAddresses(wallet.id, appId, wanted);
    return { ...pub, addresses: await this.permanentAddresses(wallet.id) };
  }

  /**
   * Aggregate wallet read — the single GET behind the 2-endpoint surface.
   * include folds in balances (ledger), addresses (watch rows) and/or a
   * paginated transaction page. Anything not included stays off the wire.
   */
  async getWalletView(
    id: string,
    appId: string,
    q: {
      include?: string;
      txLimit?: number;
      txPage?: number;
      chain?: string;
      asset?: string;
      reference?: string;
    },
  ) {
    const wallet = await this.getWalletOrThrow(id, appId);
    const inc = new Set(
      (q.include ?? 'balances,addresses').split(',').map((s) => s.trim()).filter(Boolean),
    );
    // `chain` scopes the WHOLE view — addresses, balances, transactions.
    // Resolved once up front so all three sections agree.
    let chain: string | undefined;
    if (q.chain) {
      chain = q.chain.toUpperCase();
      const valid = new Set<string>(ASSET_REGISTRY.map((a) => a.chain));
      if (!valid.has(chain)) {
        throw new BadRequestException(
          `Unsupported chain: ${q.chain} (supported: ${[...valid].join(', ')})`,
        );
      }
    }
    // accounts are custody internals (xpub + secretRef) — never on the wire.
    const { accounts: _drop, ...pub } = wallet;
    const view: Record<string, unknown> = { ...pub };
    if (inc.has('balances')) {
      const balances = await this.ledger.getBalances(id);
      view.balances = chain
        ? balances.filter((b) => getAsset(b.asset)?.chain === chain)
        : balances;
    }
    if (inc.has('addresses')) {
      const addresses = await this.permanentAddresses(id);
      view.addresses = chain
        ? addresses.filter((a) => a.chain === chain)
        : addresses;
    }
    if (inc.has('transactions')) {
      const limit = Math.min(Math.max(q.txLimit ?? 20, 1), 100);
      const page = Math.max(q.txPage ?? 1, 1);
      const where: FindOptionsWhere<Transaction> = { wallet: { id } };
      if (q.asset) {
        const asset = getAsset(q.asset);
        if (!asset) throw new BadRequestException(`Unsupported asset: ${q.asset}`);
        if (chain && asset.chain !== chain) {
          throw new BadRequestException(
            `asset ${asset.code} settles on ${asset.chain}, not ${chain} — contradictory filters`,
          );
        }
        where.asset = asset.code;
      }
      if (chain) where.chain = chain;
      if (q.reference) where.reference = q.reference;
      view.transactions = await this.txs.find({
        where,
        order: { createdAt: 'DESC' },
        take: limit,
        skip: (page - 1) * limit,
      });
    }
    return view;
  }

  async getBalances(walletId: string, appId: string) {
    await this.getWalletOrThrow(walletId, appId);
    return this.ledger.getBalances(walletId);
  }

  async getTransactions(walletId: string, appId: string) {
    await this.getWalletOrThrow(walletId, appId);
    return this.txs.find({
      where: { wallet: { id: walletId } },
      order: { createdAt: 'DESC' },
      take: 200,
    });
  }

  async listAddresses(walletId: string, appId: string) {
    await this.getWalletOrThrow(walletId, appId);
    return this.addresses.find({
      where: { account: { wallet: { id: walletId } } },
      order: { createdAt: 'DESC' },
    });
  }
}
