import {
  Inject,
  Injectable,
  Logger,
  NotFoundException,
  BadRequestException,
} from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { ConfigService } from '@nestjs/config';
import { DataSource, Repository } from 'typeorm';
import { Wallet } from '../../database/entities/wallet.entity';
import { WalletAccount } from '../../database/entities/wallet-account.entity';
import { DepositAddress } from '../../database/entities/deposit-address.entity';
import { Transaction } from '../../database/entities/transaction.entity';
import { enabledAssets, getAsset } from '../../config/assets';
import {
  BLOCKCHAIN_PROVIDER,
  BlockchainProvider,
  ChainAccountMaterial,
} from '../../providers/provider.interface';
import { LedgerService } from '../../ledger/ledger.service';
import { errMsg } from '../../common/errors';

@Injectable()
export class WalletsService {
  private readonly logger = new Logger(WalletsService.name);

  constructor(
    @InjectRepository(Wallet) private readonly wallets: Repository<Wallet>,
    @InjectRepository(WalletAccount) private readonly accounts: Repository<WalletAccount>,
    @InjectRepository(DepositAddress) private readonly addresses: Repository<DepositAddress>,
    @InjectRepository(Transaction) private readonly txs: Repository<Transaction>,
    @Inject(BLOCKCHAIN_PROVIDER) private readonly provider: BlockchainProvider,
    private readonly ledger: LedgerService,
    private readonly config: ConfigService,
    private readonly dataSource: DataSource,
  ) {}

  /**
   * Creates a wallet for a Bitlily user: one WalletAccount per enabled CHAIN.
   * All assets on a chain (ETH, USDT_ETH, USDC_ETH…) share the chain's xpub
   * and derivation counter — this is what keeps deposit addresses unique
   * per order even when multiple assets settle on one chain.
   * Wallet material (mnemonic/keys) is generated by the provider and handed
   * to the secret store — only xpubs/base addresses are persisted here.
   * Idempotent on externalUserId.
   */
  async createWallet(externalUserId: string): Promise<Wallet> {
    const existing = await this.wallets.findOne({ where: { externalUserId } });
    if (existing) return existing;

    const chains = [...new Set(enabledAssets().map((a) => a.chain))];

    const wallet = await this.dataSource.transaction(async (em) => {
      const w = await em.save(em.create(Wallet, { externalUserId }));
      for (const chain of chains) {
        const material = await this.provider.createChainAccount(chain);
        // TODO(prod): persist material.mnemonic into KMS/Vault and store only
        // the secretRef. Scaffold keeps testnet secrets in env; mnemonic is
        // intentionally NOT written to the DB.
        this.persistSecretRef(chain, material);
        await em.save(
          em.create(WalletAccount, {
            wallet: w,
            chain,
            xpub: material.xpub,
            baseAddress: material.baseAddress,
          }),
        );
      }
      return w;
    });
    return this.wallets.findOneOrFail({ where: { id: wallet.id }, relations: ['accounts'] });
  }

  private persistSecretRef(chain: string, material: ChainAccountMaterial & { mnemonic?: string }) {
    // Placeholder: in production this calls KMS/Vault. For now, if a mnemonic
    // comes back we surface a loud warning — it must never hit the DB or logs.
    if (material.mnemonic) {
      this.logger.warn(
        `Wallet material for ${chain} generated — store in KMS before production. ` +
          `Mnemonic is held in memory only and discarded.`,
      );
    }
  }

  async getWalletOrThrow(id: string): Promise<Wallet> {
    const w = await this.wallets.findOne({ where: { id }, relations: ['accounts'] });
    if (!w) throw new NotFoundException(`Wallet ${id} not found`);
    return w;
  }

  /**
   * Generates (or reuses for SOL) a deposit address for an asset.
   * `reference` ties the address to an order/invoice in the main app —
   * the Selly-style "unique address per payment" flow.
   */
  async generateDepositAddress(
    walletId: string,
    assetCode: string,
    reference?: string,
    expiresInMinutes?: number,
  ): Promise<DepositAddress> {
    const asset = getAsset(assetCode);
    if (!asset) throw new BadRequestException(`Unsupported asset: ${assetCode}`);

    const ttl = expiresInMinutes ?? this.config.get<number>('detection.addressTtlMinutes');
    const expiresAt = ttl ? new Date(Date.now() + ttl * 60_000) : null;

    return this.dataSource.transaction(async (em) => {
      // The account is per-CHAIN: USDC_ETH deposits derive from the wallet's
      // ETH account's shared index, so same-chain assets never collide.
      const account = await em.findOne(WalletAccount, {
        where: { wallet: { id: walletId }, chain: asset.chain },
        lock: { mode: 'pessimistic_write' },
      });
      if (!account) throw new NotFoundException(
        `No ${asset.chain} account for wallet ${walletId}`,
      );

      // Account-model chains (SOL) have a single base address and cannot
      // derive fresh ones. Reuse the active row: refresh reference/expiry
      // instead of colliding on the (address, asset) unique index. Per-order
      // SOL attribution needs memo/keypair-per-order — tracked as a gap.
      if (account.baseAddress) {
        const existing = await em.findOne(DepositAddress, {
          where: { account: { id: account.id }, asset: asset.code, status: 'active' },
        });
        if (existing) {
          existing.reference = reference ?? existing.reference;
          existing.expiresAt = expiresAt;
          return em.save(existing);
        }
      }

      const index = account.baseAddress ? 0 : account.nextDerivationIndex;
      const address = await this.provider.generateDepositAddress(
        { chain: account.chain as any, xpub: account.xpub, baseAddress: account.baseAddress },
        index,
      );
      if (!account.baseAddress) account.nextDerivationIndex = index + 1;
      await em.save(account);

      const dep = await em.save(
        em.create(DepositAddress, {
          account,
          address,
          chain: account.chain,
          asset: asset.code,
          derivationIndex: index,
          reference,
          expiresAt,
        }),
      );

      // Webhook mode registers provider-side monitoring; polling mode relies
      // on the DepositPoller — no per-address subscription cost.
      const useWebhooks = this.config.get('detection.strategy') === 'webhook';
      if (useWebhooks && this.provider.createAddressSubscription) {
        try {
          const sub = await this.provider.createAddressSubscription(
            address,
            account.chain as any,
          );
          dep.subscriptionId = sub.subscriptionId;
          await em.save(dep);
        } catch (e) {
          this.logger.warn(`Subscription failed for ${address}: ${errMsg(e)}`);
        }
      }
      return dep;
    });
  }

  async getBalances(walletId: string) {
    await this.getWalletOrThrow(walletId);
    return this.ledger.getBalances(walletId);
  }

  async getTransactions(walletId: string) {
    await this.getWalletOrThrow(walletId);
    return this.txs.find({
      where: { wallet: { id: walletId } },
      order: { createdAt: 'DESC' },
      take: 200,
    });
  }

  async listAddresses(walletId: string) {
    return this.addresses.find({
      where: { account: { wallet: { id: walletId } } },
      order: { createdAt: 'DESC' },
    });
  }
}
